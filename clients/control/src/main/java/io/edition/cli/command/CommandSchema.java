package io.edition.cli.command;

import static io.edition.cli.shared.JsonSupport.JSON;

import com.fasterxml.jackson.databind.JsonNode;
import com.fasterxml.jackson.databind.node.*;
import io.edition.cli.contract.ContractCatalog;
import io.edition.cli.shared.CliFailure;
import java.util.*;

/** 按需把契约投影为方法/类型说明，供 schema 命令发现参数；不维护第二份参数定义。 */
final class CommandSchema {
    private final ContractCatalog catalog;
    private final CliCommand root;

    CommandSchema(ContractCatalog catalog) {
        this(catalog, null);
    }

    CommandSchema(ContractCatalog catalog, CliCommand root) {
        this.catalog = catalog;
        this.root = root;
    }

    JsonNode describe(String name, boolean expand) throws Exception {
        if (name.equals("control.BatchRequest")) return ApiBatch.schema();
        var command = command(name);
        String methodName = name;
        if (name.endsWith(".+inspect")) {
            methodName = name.equals("control.spaces.pages.+inspect")
                    ? "control.spaces.pages.content.get"
                    : name.replace(".+inspect", ".get");
        }
        JsonNode op = catalog.operation(methodName), value;
        if (op == null) {
            if (command != null) {
                var children = command.getAllChildParsers();
                var local = JSON.createObjectNode().put("kind", children.isEmpty() ? "localHelper" : "commandGroup");
                local.set("cli", cli(command, name));
                if (!children.isEmpty()) {
                    var subcommands = local.putArray("subcommands");
                    for (var child : children) {
                        var model = child.getProcessedCommand();
                        subcommands
                                .addObject()
                                .put("command", ((CliCommand) child).qualifiedName)
                                .put("schema", name + "." + model.name())
                                .put("description", model.description());
                    }
                }
                return local;
            }
            if (!name.matches("control\\.[A-Z][A-Za-z0-9_]*")) throw unknown();
            try {
                value = catalog.schema("#/components/schemas/" + name.substring(8));
            } catch (java.io.UncheckedIOException e) {
                throw unknown();
            }
        } else {
            var method = JSON.createObjectNode()
                    .put("httpMethod", op.path("method").asText())
                    .put("path", op.path("path").asText().replaceFirst("^/", ""))
                    .put("description", description(op));
            method.put("readOnly", !op.path("mutates").asBoolean());
            var parameters = method.putObject("parameters");
            var order = method.putArray("parameterOrder");
            for (var p : op.path("parameters")) {
                var definition = p.has("schema")
                        ? (ObjectNode) p.path("schema").deepCopy()
                        : JSON.createObjectNode().put("type", "string");
                definition
                        .put("required", p.path("required").asBoolean())
                        .put("location", p.path("in").asText());
                if (p.has("description"))
                    definition.put("description", p.path("description").asText());
                if (p.path("name").asText().equals("Idempotency-Key"))
                    definition.put("description", "Stable original intent key; generated by the CLI when omitted.");
                parameters.set(p.path("name").asText(), definition);
                if (p.path("in").asText().equals("path"))
                    order.add(p.path("name").asText());
            }
            if (order.isEmpty()) method.remove("parameterOrder");
            method.set("scopes", op.path("requiredScopes"));
            method.set("credentialTypes", op.path("credentialTypes"));
            method.put("idempotencyMode", op.path("idempotencyMode").asText());
            method.put("confirmationRequired", op.path("highImpact").asBoolean());
            JsonNode bodyContent = op.path("requestBody").path("content");
            if (!bodyContent.isEmpty()) {
                // 保留 JSON 的短类型入口，也公开上传可用的 HTTP 媒体类型。
                JsonNode media = bodyContent.has("application/json")
                        ? bodyContent.path("application/json")
                        : bodyContent.elements().next();
                var body = type(media.path("schema"));
                if (bodyContent.has("application/json")) body.set("schema", catalog.bodySchema(op));
                var contentTypes = body.putArray("contentTypes");
                bodyContent.fieldNames().forEachRemaining(contentTypes::add);
                method.set("requestBody", body);
            }
            for (var responses = op.path("responses").properties().iterator(); responses.hasNext(); ) {
                var response = responses.next();
                if (response.getKey().startsWith("2")) {
                    var content = response.getValue().path("content");
                    // Spring 可能用通配媒体类型声明 JSON；不能因此遗漏响应类型。
                    for (var media : content) {
                        if (media.has("schema")) {
                            method.set("response", type(media.path("schema")));
                            break;
                        }
                    }
                    if (method.has("response")) break;
                }
            }
            value = method;
        }
        if (command != null) {
            ((ObjectNode) value).put("apiMethod", methodName);
            ((ObjectNode) value).set("cli", cli(command, name));
        }
        return refs(value, expand, new LinkedHashSet<>(), new int[] {0}, 0);
    }

    /** 只裁剪 CLI 展示元数据；原生 schema（含空数组/null）和方法约束完整保留。 */
    JsonNode describe(String name, boolean expand, boolean brief) throws Exception {
        var value = describe(name, expand);
        if (!brief || !(value.path("cli") instanceof ObjectNode cli)) return value;
        if (cli.path("description").equals(value.path("description"))) cli.remove("description");
        var options = (ObjectNode) cli.path("options");
        String constraints = cli.path("constraints").toString();
        for (String option : List.of("--profile", "--format", "--file-root", "--timeout", "--help", "--version")) {
            if (!options.path(option).path("required").asBoolean() && !constraints.contains('"' + option + '"'))
                options.remove(option);
        }
        if (cli.path("examples") instanceof ArrayNode examples) {
            for (int i = examples.size() - 1; i >= 0; i--)
                if (examples.get(i).asText().startsWith("editionctl schema ")) examples.remove(i);
        }
        for (String field : List.of("options", "arguments", "constraints", "examples"))
            if (cli.path(field).isEmpty()) cli.remove(field);
        return value;
    }

    private CliCommand command(String name) {
        if (root == null) return null;
        var current = root;
        for (String part : name.split("\\.")) {
            var child = current.child(part);
            if (child == null) return null;
            current = child;
        }
        return current;
    }

    /** CLI 语法从实际解析器投影；HTTP 参数和类型仍由原契约提供，避免另造帮助目录。 */
    private ObjectNode cli(CliCommand spec, String name) {
        var result = JSON.createObjectNode()
                .put("command", spec.qualifiedName)
                .put("description", spec.getProcessedCommand().description());
        var options = result.putObject("options");
        for (var option : spec.options()) {
            var field = options.putObject(("--" + option.name()))
                    .put(
                            "type",
                            option.type() == Boolean.class || option.type() == boolean.class
                                    ? "boolean"
                                    : option.type() == Integer.class
                                                    || option.type() == int.class
                                                    || option.type() == Long.class
                                                    || option.type() == long.class
                                            ? "integer"
                                            : "string")
                    .put("required", option.isRequired())
                    .put("description", option.description());
            if (!option.getDefaultValues().isEmpty())
                field.put("default", option.getDefaultValues().getFirst());
            field.put(
                    "input",
                    switch (("--" + option.name())) {
                        case "--params" -> "nativeApiParameters";
                        case "--json" -> name.equals("control.+batch") ? "batchRequest" : "nativeApiBody";
                        case "--upload" -> "nativeApiBinaryBody";
                        default -> "cliOption";
                    });
        }
        var arguments = result.putArray("arguments");
        for (var argument : spec.getProcessedCommand().getPositionalOptionsInDisplayOrder()) {
            var range = argument.getIndexRange();
            String index = String.valueOf(range.getMin());
            if (range.getMin() != range.getMax())
                index += ".." + (range.getMax() == Integer.MAX_VALUE ? "*" : range.getMax());
            arguments
                    .addObject()
                    .put("index", index)
                    .put("required", argument.isRequired())
                    .put("description", argument.description());
        }
        var constraints = result.putArray("constraints");
        if (options.has("--json") && options.has("--upload"))
            constraints.addObject().putArray("mutuallyExclusive").add("--json").add("--upload");
        if (options.has("--params") && options.has("--json"))
            constraints
                    .addObject()
                    .putArray("atMostOneStdinConsumer")
                    .add("--params")
                    .add("--json");
        if (options.has("--new-invocation"))
            constraints
                    .addObject()
                    .putArray("mutuallyExclusive")
                    .add("--new-invocation")
                    .add("--invocation-id");
        if (options.has("--wait")) {
            constraints
                    .addObject()
                    .putArray("requiresWait")
                    .add("--wait-timeout")
                    .add("--wait-attempts")
                    .add("--wait-interval");
        }
        var output = result.putObject("output").put("encoding", name.equals("control.+batch") ? "ndjson" : "json");
        output.put(
                "shape",
                name.endsWith(".+inspect")
                        ? "httpObservation(status,body,headers)"
                        : name.equals("control.+batch")
                                ? "itemResultsThenRequestSummary"
                                : name.equals("control.+receipt")
                                        ? "privateOriginalIntentReceipt"
                                        : name.equals("control.+resume")
                                                ? "originalApiResultPossiblyHistorical"
                                                : name.equals("config.inspect")
                                                        ? "localCredentialSourceDiagnostic"
                                                        : "nativeResult");
        if (options.has("--page-all")) output.put("pageAllEncoding", "ndjsonOneApiPagePerLine");
        if (options.has("--wait"))
            output.put(
                    "waitShape",
                    "wait(state,successful,attempts,budget),observation; terminal does not imply requested business success");
        if (name.equals("control.+batch")) {
            result.put("inputSchemaRef", "control.BatchRequest");
            output.put(
                    "completion", "Summary counts finished request calls; it does not verify background completion.");
        }
        var examples = result.putArray("examples");
        for (String example : spec.examples()) {
            if (example.strip().startsWith("editionctl ")) examples.add(example.strip());
        }
        return result;
    }

    private ObjectNode type(JsonNode schema) {
        var result = JSON.createObjectNode();
        if (schema.has("$ref"))
            result.put("schemaRef", schema.path("$ref").asText().replace("#/components/schemas/", ""));
        result.set("schema", catalog.resolve(schema));
        return result;
    }

    private JsonNode refs(JsonNode source, boolean expand, Set<String> seen, int[] count, int depth) {
        if (++count[0] > 10000 || depth > 32)
            throw CliFailure.input(
                    "Schema expansion exceeds its limit.", "Query the referenced control.Type individually.");
        if (source.isObject()) {
            String ref = source.path("$ref").asText();
            if (expand && !ref.isEmpty() && seen.add(ref)) {
                var resolved = refs(catalog.schema(ref), true, seen, count, depth + 1);
                seen.remove(ref);
                if (source.size() == 1) return resolved;
                var siblings = (ObjectNode) source.deepCopy();
                siblings.remove("$ref");
                var result = JSON.createObjectNode();
                result.putArray("allOf").add(resolved).add(refs(siblings, true, seen, count, depth + 1));
                return result;
            }
            var result = JSON.createObjectNode();
            source.properties()
                    .iterator()
                    .forEachRemaining(e -> result.set(
                            e.getKey(),
                            e.getKey().equals("$ref")
                                    ? JSON.getNodeFactory()
                                            .textNode(e.getValue().asText().replace("#/components/schemas/", ""))
                                    : refs(e.getValue(), expand, seen, count, depth + 1)));
            return result;
        }
        if (source.isArray()) {
            var array = JSON.createArrayNode();
            source.forEach(n -> array.add(refs(n, expand, seen, count, depth + 1)));
            return array;
        }
        return source;
    }

    private String description(JsonNode op) {
        String description = op.path("description").asText();
        if (op.path("credentialTypes").size() == 1)
            description += " Credential: " + op.path("credentialTypes").get(0).asText() + ".";
        if (op.path("mutates").asBoolean()
                && !op.path("capabilities").path("invocation").asBoolean())
            description += " No local replay receipt. Query an unknown outcome before another attempt.";
        return description;
    }

    private static CliFailure unknown() {
        return CliFailure.input(
                "Unknown method or type.", "editionctl control --help; editionctl schema control.spaces.list");
    }
}
